CREATE TABLE IF NOT EXISTS filmrating (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS film (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL,
    description VARCHAR(200) NOT NULL,
    releaseDate DATE,
    duration INT,
    ratingId BIGINT NOT NULL,
    FOREIGN KEY (ratingId) REFERENCES filmrating (id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS genre (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS filmGenre (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filmId BIGINT NOT NULL,
    genreId BIGINT NOT NULL,
    FOREIGN KEY (genreId) REFERENCES genre (id) ON DELETE CASCADE,
    FOREIGN KEY (filmId) REFERENCES film (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL,
    email VARCHAR(32) NOT NULL,
    login VARCHAR(32) NOT NULL,
    birthday DATE
);

CREATE TABLE IF NOT EXISTS friends (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId BIGINT NOT NULL,
    friendId BIGINT NOT NULL,
    FOREIGN KEY (userId) REFERENCES users (id) ON DELETE CASCADE,
    FOREIGN KEY (friendId) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS friendRequest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId BIGINT NOT NULL,
    friendId BIGINT NOT NULL,
    accept BOOLEAN,
    FOREIGN KEY (userId) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS likedUsers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filmId BIGINT NOT NULL,
    userId BIGINT NOT NULL,
    FOREIGN KEY (filmId) REFERENCES film (id) ON DELETE CASCADE,
    FOREIGN KEY (userId) REFERENCES users (id) ON DELETE CASCADE
);

-- Таблица отзывов
CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(1000) NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id BIGINT NOT NULL,
    film_id BIGINT NOT NULL,
    useful INTEGER DEFAULT 0,
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    FOREIGN KEY (film_id) REFERENCES film (id) ON DELETE CASCADE
);

-- Таблица для хранения лайков/дизлайков отзывов
CREATE TABLE IF NOT EXISTS review_ratings (
    review_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    rating INTEGER NOT NULL, -- +1 для лайка, -1 для дизлайка
    PRIMARY KEY (review_id, user_id),
    FOREIGN KEY (review_id) REFERENCES reviews (review_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);